// Regenerates README.md: screenshots of the running app into docs/images/,
// then fills scripts/readme/template.md with them and with facts read from the
// repo (examples, built-in parts, test count).
//
//   npm run readme                  # screenshots + README
//   npm run readme -- --no-shots    # README text only, keep existing images
//   npm run readme -- --only=hero   # retake some screenshots

import { execFileSync, spawn } from "node:child_process";
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import electron from "electron";
import { build, preview } from "vite";
import { BUILTIN_LIBRARY } from "../../src/shared/library";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const IMAGES = join(ROOT, "docs", "images");
const args = process.argv.slice(2);
const only = args.find((a) => a.startsWith("--only="));

async function screenshots() {
  // A production build, not the dev server: the dev server can reload the page
  // mid-shot when it discovers a dependency to pre-bundle.
  const configFile = join(ROOT, "vite.renderer.config.ts");
  const outDir = join(ROOT, "out", "readme");
  await build({ configFile, logLevel: "warn", build: { outDir, emptyOutDir: true, chunkSizeWarningLimit: 4096 } });
  const server = await preview({ configFile, logLevel: "warn", build: { outDir }, preview: { port: 0, strictPort: false } });
  const url = server.resolvedUrls!.local[0];
  console.log(`Capturing screenshots from ${url}`);
  try {
    const code = await new Promise<number>((resolve, reject) => {
      const child = spawn(electron as unknown as string, [
        join(ROOT, "scripts", "readme", "capture.cjs"), `--url=${url}`, `--out=${IMAGES}`, `--root=${ROOT}`, ...(only ? [only] : []),
      ], { stdio: "inherit" });
      child.on("error", reject);
      child.on("exit", (c) => resolve(c ?? 1));
    });
    if (code) throw new Error("screenshot capture failed (see above)");
  } finally {
    await server.close();
  }
}

/** Test count from vitest itself, so the README never drifts. */
function testCount(): number {
  const out = execFileSync(process.execPath, [join(ROOT, "node_modules", "vitest", "vitest.mjs"), "list", "--json"], { cwd: ROOT, encoding: "utf8" });
  return (JSON.parse(out.slice(out.indexOf("["))) as unknown[]).length;
}

function examples(): string {
  return readdirSync(join(ROOT, "examples"))
    .filter((f) => f.endsWith(".dad"))
    .sort()
    .map((f) => {
      const p = JSON.parse(readFileSync(join(ROOT, "examples", f), "utf8")) as { name: string; parts: unknown[] };
      const [, num, title] = /^(\d+)\s+(.*)$/.exec(p.name) ?? [, "", p.name];
      return `| ${num} | ${title} | ${p.parts.length} | [\`${f}\`](examples/${encodeURI(f)}) |`;
    })
    .join("\n");
}

const CATEGORIES: Record<string, string> = {
  mcu: "Microcontrollers", logic: "Logic", "analog-ic": "Analogue ICs", semiconductor: "Discretes",
  passive: "Passives", source: "Sources", indicator: "Indicators", peripheral: "Inputs and displays",
  instrument: "Instruments", terminal: "Terminals", misc: "Other",
};

function parts(): string {
  const byCat = new Map<string, string[]>(Object.keys(CATEGORIES).map((c) => [c, []]));
  for (const d of BUILTIN_LIBRARY) byCat.get(d.category)?.push(`\`${d.id}\``);
  return [...byCat].filter(([, ids]) => ids.length).map(([c, ids]) => `| ${CATEGORIES[c]} | ${ids.join(" ")} |`).join("\n");
}

function render() {
  const template = readFileSync(join(ROOT, "scripts", "readme", "template.md"), "utf8");
  const vars: Record<string, () => string> = {
    tests: () => String(testCount()),
    examples,
    parts,
    version: () => JSON.parse(readFileSync(join(ROOT, "package.json"), "utf8")).version,
  };
  const out = template
    // Template comments are notes for whoever edits it; they don't ship.
    .replace(/<!--\s*template:[\s\S]*?-->\n?/g, "")
    .replace(/\{\{(\w+)\}\}/g, (m, k: string) => {
      if (!vars[k]) throw new Error(`template: unknown variable ${m}`);
      return vars[k]();
    });
  for (const [, src] of out.matchAll(/!\[[^\]]*\]\(([^)]+\.png)\)/g)) {
    if (!existsSync(join(ROOT, src))) throw new Error(`README references missing image ${src}`);
  }
  writeFileSync(join(ROOT, "README.md"), `<!-- Generated by \`npm run readme\` from scripts/readme/template.md. Edit the template, not this file. -->\n\n${out}`);
  console.log(`Wrote ${relative(process.cwd(), join(ROOT, "README.md"))}`);
}

if (!args.includes("--no-shots")) await screenshots();
render();
