const cache = new Map<number, number[]>();

/** Seven row bitmasks (bit 4 = leftmost column) for a character code. */
export function lcdGlyph(code: number): number[] {
  const hit = cache.get(code);
  if (hit) return hit;
  const hex = code >= 0x20 && code < 0x80 ? COLS[code - 0x20] ?? "" : "";
  let rows: number[];
  if (hex.length < 10) {
    rows = code >= 0x80 ? [0x1f, 0x1f, 0x1f, 0x1f, 0x1f, 0x1f, 0x1f] : [0, 0, 0, 0, 0, 0, 0];
  } else {
    const cols = [0, 1, 2, 3, 4].map((i) => parseInt(hex.slice(i * 2, i * 2 + 2), 16));
    rows = [0, 1, 2, 3, 4, 5, 6].map((y) => cols.reduce((acc, c, x) => acc | (((c >> y) & 1) << (4 - x)), 0));
  }
  cache.set(code, rows);
  return rows;
}
